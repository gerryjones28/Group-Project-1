# 01_size_limits_check.R ------------------------------------------------------
# Answers the practical question: "Can these files open in Excel / Google
# Sheets, or are they too large?"  Produces EDA/reports/size_limits_check.csv
# (one row per file) and a human-readable markdown version.
#
# Usage:  Rscript EDA/scripts/01_size_limits_check.R

.self_dir <- function() {
  a <- commandArgs(trailingOnly = FALSE); h <- grep("^--file=", a, value = TRUE)
  if (length(h)) normalizePath(dirname(sub("^--file=", "", h[[1]]))) else normalizePath(getwd())
}
source(file.path(.self_dir(), "00_common.R"))

require_files(c(INST_LATEST, FOS_LATEST), "the most-recent Scorecard snapshots")

log_step("scanning ", DATA_DIR)

files <- list.files(DATA_DIR, pattern = "\\.csv$", full.names = TRUE, recursive = TRUE)
files <- c(files, list.files(file.path(PROJECT_ROOT, "data"),
                             pattern = "\\.zip$", full.names = TRUE))
files <- sort(files)

# ---------------------------------------------------------------------------
# Measure every file: size, rows, columns, cells
# ---------------------------------------------------------------------------
   
res <- rbindlist(lapply(files, function(f) {
  is_zip <- grepl("\\.zip$", f)
  bytes  <- file.size(f)
  if (is_zip) {
    # 469 MB archive of the very same 06032026 folder: list its members instead
    inner <- tryCatch(system2("unzip", c("-Z1", shQuote(f)), stdout = TRUE), error = function(e) character())
    data.table(file = basename(f), group = "zip archive", rows = NA_integer_,
               cols = NA_integer_, bytes = bytes,
               note = sprintf("archive; contains %d entries (duplicate of the extracted folder)",
                              length(inner)))
  } else {
    hdr <- csv_header(f)
    data.table(file = basename(f),
               group = if (grepl("^MERGED", basename(f))) "yearly institution file (MERGED)"
                       else if (grepl("^FieldOfStudyData", basename(f))) "field-of-study file by year"
                       else "most-recent snapshot",
               rows = count_rows(f), cols = length(hdr), bytes = bytes, note = "")
  }
}), fill = TRUE)

res[, cells := as.numeric(rows) * as.numeric(cols)]
res[, mb    := round(bytes / 1024^2, 1)]

# ---------------------------------------------------------------------------
# Verdicts against the real limits
# ---------------------------------------------------------------------------
res[, `:=`(
  fits_gsheets_cells = cells <= GSheets_MAX_CELLS,
  fits_gsheets_size  = bytes <= GSheets_MAX_BYTES,
  fits_excel_shape   = rows <= Excel_MAX_ROWS & cols <= Excel_MAX_COLS
)]
res[, opens_in_gsheets := fifelse(is.na(cells), "n/a (archive)",
                           fifelse(fits_gsheets_cells & fits_gsheets_size, "yes",
                            paste0("no (",
                              fifelse(!fits_gsheets_cells,
                                      paste0(fnum(cells), " cells > 10,000,000"), ""),
                              fifelse(!fits_gsheets_cells & !fits_gsheets_size, "; ", ""),
                              fifelse(!fits_gsheets_size,
                                      paste0(mb, " MB > 100 MB"), ""), ")")))]
res[, opens_in_excel := fifelse(is.na(cells), "n/a (archive)",
                         fifelse(!fits_excel_shape, "no (too many rows/columns)",
                          fifelse(cells > COMFORT_CELLS | bytes > COMFORT_BYTES,
                                  "yes, but very slow / memory hungry", "yes")))]
res[, cells_left_under_gsheets_limit := GSheets_MAX_CELLS - cells]

setcolorder(res, c("group", "file", "rows", "cols", "cells", "mb",
                   "opens_in_gsheets", "opens_in_excel", "note"))

out_csv <- file.path(REPORTS_DIR, "size_limits_check.csv")
fwrite(res, out_csv)

# ---------------------------------------------------------------------------
# How many columns *would* fit? (useful when subsetting a file by hand)
# ---------------------------------------------------------------------------
inst_rows <- res[group == "most-recent snapshot" & grepl("Institution", file), rows]
budget <- data.table(
  scenario = c("600 rows (single page)", "6,273 rows (all institutions, most-recent snapshot)",
               "228,000 rows (field-of-study snapshot)", "210,000 rows (30-year panel)"),
  max_cols_for_gsheets = floor(GSheets_MAX_CELLS / c(600, 6273, 228000, 210000)),
  max_cols_for_comfort  = floor(COMFORT_CELLS / c(600, 6273, 228000, 210000)))
fwrite(budget, file.path(REPORTS_DIR, "column_budget_vs_cell_limits.csv"))

# ---------------------------------------------------------------------------
# Markdown summary
# ---------------------------------------------------------------------------
Y <- function(x) ifelse(x, "yes", "no")
summary_md <- c(
  "# Size / limit check (generated by 01_size_limits_check.R)",
  "",
  sprintf("Data folder: `%s`", DATA_DIR),
  sprintf("Files scanned: %d (%s total on disk)", nrow(res), paste0(round(sum(res$bytes) / 1024^3, 2), " GB")),
  "",
  "Hard limits used:",
  sprintf("- Google Sheets: %s cells per spreadsheet (all tabs combined), ~100 MB upload for conversion", fnum(GSheets_MAX_CELLS)),
  sprintf("- Excel .xlsx sheet: %s rows x %s columns", fnum(Excel_MAX_ROWS), fnum(Excel_MAX_COLS)),
  "",
  "## Verdict per file",
  "",
  md_table(res[, .(group, file, rows, cols, cells = fnum(cells), MB = mb,
                   Google_Sheets = opens_in_gsheets, Excel = opens_in_excel)]),
  "",
  "## How many columns fit inside the Google Sheets cell limit",
  "",
  md_table(budget),
  "")
writeLines(summary_md, file.path(REPORTS_DIR, "size_limits_check.md"))

log_step("wrote ", out_csv)
print(res[, .(file, rows, cols, cells = fnum(cells), MB = mb,
              gsheets = opens_in_gsheets, excel = opens_in_excel)])
